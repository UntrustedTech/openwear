#!/usr/bin/env python3
"""Generates every OpenWear icon from one design.

The mark: a band (capsule) outline with an orange pulse line that runs
through it and out the other side, on the app's near-black background.
Geometry is in the 108-unit space of an Android adaptive icon (safe zone
is the centred 66-unit circle).

Run from anywhere:  python3 brand/make_icons.py
Writes into app/android/app/src/main/res, band-app/src/logo.png and
brand/ (SVG master + previews). Needs Pillow.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/android/app/src/main/res"
BRAND = ROOT / "brand"

BACKGROUND = "#0C0C0E"
BAND = "#F2F0E9"
PULSE = "#FF5B1F"

# Capsule: x 38–70, y 26–82, corner radius 16 (a band's pill-shaped screen).
CAP_X0, CAP_Y0, CAP_X1, CAP_Y1, CAP_R = 38, 26, 70, 82, 16
CAP_STROKE = 4.5
# Pulse: flat, a beat inside the band, flat again.
PULSE_POINTS = [(23, 54), (45.5, 54), (49.5, 42), (54.5, 66), (59, 46), (62.5, 54), (85, 54)]
PULSE_STROKE = 4.6
HALO_STROKE = 11.0  # background-coloured gap where the pulse crosses the band

CAPSULE_PATH = (
    f"M{CAP_X0},{CAP_Y0 + CAP_R} "
    f"a{CAP_R},{CAP_R} 0 0 1 {2 * CAP_R},0 "
    f"v{CAP_Y1 - CAP_Y0 - 2 * CAP_R} "
    f"a{CAP_R},{CAP_R} 0 0 1 {-2 * CAP_R},0 z"
)
PULSE_PATH = "M" + " L".join(f"{x},{y}" for x, y in PULSE_POINTS)


# --- Android vector drawables -------------------------------------------------

def _stroke_path(path, color, width):
    return (
        f'    <path android:pathData="{path}" android:strokeColor="{color}" '
        f'android:strokeWidth="{width}" android:strokeLineCap="round" '
        f'android:strokeLineJoin="round" android:fillColor="#00000000" />\n'
    )


def _vector(body, size="108dp", viewport=108, group=None):
    head = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by brand/make_icons.py; edit that instead. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}" android:height="{size}"\n'
        f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n'
    )
    if group:
        body = f"  <group {group}>\n{body}  </group>\n"
    return head + body + "</vector>\n"


def write_vectors():
    drawable = RES / "drawable"
    drawable.mkdir(parents=True, exist_ok=True)
    foreground = (
        _stroke_path(CAPSULE_PATH, BAND, CAP_STROKE)
        + _stroke_path(PULSE_PATH, BACKGROUND, HALO_STROKE)
        + _stroke_path(PULSE_PATH, PULSE, PULSE_STROKE)
    )
    (drawable / "ic_launcher_foreground.xml").write_text(_vector(foreground))
    # Themed icons (Android 13+) use only the shape: one colour, no gap.
    mono = _stroke_path(CAPSULE_PATH, "#FFFFFFFF", CAP_STROKE) + _stroke_path(
        PULSE_PATH, "#FFFFFFFF", PULSE_STROKE
    )
    (drawable / "ic_launcher_monochrome.xml").write_text(_vector(mono))
    # Status bar: white on transparent, the safe zone cropped, bolder lines.
    status = _stroke_path(CAPSULE_PATH, "#FFFFFFFF", 6.5) + _stroke_path(
        PULSE_PATH, "#FFFFFFFF", 7
    )
    (drawable / "ic_stat_openwear.xml").write_text(
        _vector(
            status,
            size="24dp",
            viewport=68,
            group='android:translateX="-20" android:translateY="-20"',
        )
    )

    values = RES / "values"
    values.mkdir(exist_ok=True)
    (values / "ic_launcher_colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by brand/make_icons.py; edit that instead. -->\n"
        "<resources>\n"
        f'    <color name="openwear_background">{BACKGROUND}</color>\n'
        "</resources>\n"
    )
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by brand/make_icons.py; edit that instead. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/openwear_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / name).write_text(adaptive)


# --- Bitmaps ------------------------------------------------------------------

SUPERSAMPLE = 8


def _mark(size, crop=(18, 90), halo=True):
    """The mark on the background, [crop] of the 108 space filling [size] px."""
    s = size * SUPERSAMPLE
    img = Image.new("RGBA", (s, s), BACKGROUND)
    d = ImageDraw.Draw(img)
    lo, hi = crop
    k = s / (hi - lo)

    def p(x, y):
        return ((x - lo) * k, (y - lo) * k)

    def line(points, color, width):
        pts = [p(x, y) for x, y in points]
        w = max(1, round(width * k))
        d.line(pts, fill=color, width=w, joint="curve")
        r = w / 2
        for x, y in (pts[0], pts[-1]):
            d.ellipse((x - r, y - r, x + r, y + r), fill=color)

    x0, y0 = p(CAP_X0, CAP_Y0)
    x1, y1 = p(CAP_X1, CAP_Y1)
    d.rounded_rectangle(
        (x0, y0, x1, y1),
        radius=CAP_R * k,
        outline=BAND,
        width=max(1, round(CAP_STROKE * k)),
    )
    if halo:
        line(PULSE_POINTS, BACKGROUND, HALO_STROKE)
    line(PULSE_POINTS, PULSE, PULSE_STROKE)
    return img


def _masked(img, size, shape):
    s = img.size[0]
    mask = Image.new("L", (s, s), 0)
    md = ImageDraw.Draw(mask)
    if shape == "circle":
        md.ellipse((0, 0, s - 1, s - 1), fill=255)
    else:
        md.rounded_rectangle((0, 0, s - 1, s - 1), radius=s * 0.22, fill=255)
    out = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    out.paste(img, (0, 0), mask)
    return out.resize((size, size), Image.LANCZOS)


LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write_bitmaps():
    for density, px in LEGACY.items():
        folder = RES / f"mipmap-{density}"
        folder.mkdir(exist_ok=True)
        _masked(_mark(px), px, "square").save(folder / "ic_launcher.png")
        _masked(_mark(px), px, "circle").save(folder / "ic_launcher_round.png")
    # Vela quick app icon on the band: round, 120 px like the toolkit's.
    band_logo = ROOT / "band-app/src/logo.png"
    _masked(_mark(120, crop=(16, 92)), 120, "circle").save(band_logo)
    # Store listing / README sizes.
    BRAND.mkdir(exist_ok=True)
    _masked(_mark(512), 512, "square").save(BRAND / "openwear-icon-512.png")
    _mark(1024).resize((1024, 1024), Image.LANCZOS).save(
        BRAND / "openwear-icon-full-1024.png"
    )


def write_svg():
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">
  <!-- OpenWear mark. Generated by brand/make_icons.py; edit that instead. -->
  <rect x="18" y="18" width="72" height="72" rx="16" fill="{BACKGROUND}"/>
  <g fill="none" stroke-linecap="round" stroke-linejoin="round">
    <path d="{CAPSULE_PATH}" stroke="{BAND}" stroke-width="{CAP_STROKE}"/>
    <path d="{PULSE_PATH}" stroke="{BACKGROUND}" stroke-width="{HALO_STROKE}"/>
    <path d="{PULSE_PATH}" stroke="{PULSE}" stroke-width="{PULSE_STROKE}"/>
  </g>
</svg>
"""
    (BRAND / "openwear-icon.svg").write_text(svg)


if __name__ == "__main__":
    write_vectors()
    write_bitmaps()
    write_svg()
    print("icons written")
